"""Opt-in PostgreSQL tests; each test rolls back its temporary schema and data."""
import os
import unittest
import uuid

from sqlalchemy import inspect, text
from sqlalchemy.exc import DBAPIError
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

from scripts.align_existing_schema import align_schema

URL = os.getenv("ASYNCTICKET_TEST_DATABASE_URL")


@unittest.skipUnless(URL, "Set ASYNCTICKET_TEST_DATABASE_URL to a dedicated local PostgreSQL database.")
class SchemaAlignmentTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        url = make_url(URL)
        if url.host not in ("localhost", "127.0.0.1", "::1") or not any(x in url.database for x in ("test", "local")):
            self.fail("Use a dedicated local test database.")
        self.engine = create_async_engine(url)
        self.connection = await self.engine.connect()
        self.transaction = await self.connection.begin()
        self.schema = "alignment_" + uuid.uuid4().hex
        await self.connection.execute(text(f'CREATE SCHEMA "{self.schema}"'))

    async def asyncTearDown(self):
        await self.transaction.rollback()
        await self.connection.close()
        await self.engine.dispose()

    async def fixture(self, *, identity=False):
        s = self.schema
        identity_sql = "GENERATED BY DEFAULT AS IDENTITY" if identity else ""
        for ddl in (
            f'CREATE TABLE "{s}".blacklist (black_id BIGINT {identity_sql} PRIMARY KEY, user_id BIGINT NOT NULL, jti_token VARCHAR(255) NOT NULL, expired_at TIMESTAMPTZ NOT NULL)',
            f'CREATE TABLE "{s}".payments (reserv_id BIGINT NOT NULL)',
            f'CREATE TABLE "{s}".performance_seats (reserv_id BIGINT NOT NULL)',
            f"INSERT INTO \"{s}\".blacklist (black_id,user_id,jti_token,expired_at) VALUES (10,20,'retained-token','2026-01-01Z')",
        ):
            await self.connection.execute(text(ddl))

    async def assert_preserved_and_usable(self):
        s = self.schema
        before = (await self.connection.execute(text(f'SELECT * FROM "{s}".blacklist'))).one()
        self.assertTrue(await align_schema(self.connection, s))
        after = (await self.connection.execute(text(f'SELECT * FROM "{s}".blacklist WHERE jti_token=\'retained-token\''))).one()
        self.assertEqual(before, after)
        await self.connection.execute(text(f"INSERT INTO \"{s}\".blacklist (jti_token,expired_at) VALUES ('new-token','2026-02-01Z')"))
        for name in ("payments", "performance_seats"):
            await self.connection.execute(text(f'INSERT INTO "{s}".{name} (reserv_id) VALUES (NULL)'))
        self.assertEqual(await align_schema(self.connection, s), [])
        pk = await self.connection.run_sync(lambda c: inspect(c).get_pk_constraint("blacklist", schema=s))
        self.assertEqual(pk["constrained_columns"], ["jti_token"])

    async def test_preserves_legacy_values_and_supports_new_inserts_idempotently(self):
        await self.fixture()
        await self.assert_preserved_and_usable()

    async def test_retains_legacy_identity_and_supports_new_inserts(self):
        await self.fixture(identity=True)
        await self.assert_preserved_and_usable()

    async def test_duplicate_tokens_fail_without_deleting_rows_or_changing_pk(self):
        await self.fixture()
        s = self.schema
        await self.connection.execute(text(f"INSERT INTO \"{s}\".blacklist VALUES (11,21,'retained-token','2026-02-01Z')"))
        with self.assertRaisesRegex(ValueError, "duplicate"):
            await align_schema(self.connection, s)
        self.assertEqual(await self.connection.scalar(text(f'SELECT count(*) FROM "{s}".blacklist')), 2)
        pk = await self.connection.run_sync(lambda c: inspect(c).get_pk_constraint("blacklist", schema=s))
        self.assertEqual(pk["constrained_columns"], ["black_id"])

    async def test_later_error_rolls_back_all_schema_changes(self):
        await self.fixture()
        s = self.schema
        nested = await self.connection.begin_nested()
        await align_schema(self.connection, s)
        await nested.rollback()
        pk = await self.connection.run_sync(lambda c: inspect(c).get_pk_constraint("blacklist", schema=s))
        self.assertEqual(pk["constrained_columns"], ["black_id"])
        nullable = await self.connection.run_sync(lambda c: {x['name']:x['nullable'] for x in inspect(c).get_columns('payments',schema=s)})
        self.assertFalse(nullable['reserv_id'])

    async def test_unexpected_foreign_key_blocks_key_change_and_preserves_schema(self):
        await self.fixture()
        s = self.schema
        await self.connection.execute(text(f'CREATE TABLE "{s}".legacy_reference (black_id BIGINT REFERENCES "{s}".blacklist(black_id))'))
        nested = await self.connection.begin_nested()
        with self.assertRaises(DBAPIError):
            await align_schema(self.connection, s)
        await nested.rollback()
        pk = await self.connection.run_sync(lambda c: inspect(c).get_pk_constraint("blacklist", schema=s))
        self.assertEqual(pk["constrained_columns"], ["black_id"])
        self.assertEqual(await self.connection.scalar(text(f'SELECT count(*) FROM "{s}".blacklist')), 1)
